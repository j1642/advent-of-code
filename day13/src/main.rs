use day13::{day_13_1, day_13_2};
use std::fs;

fn main() {
    let text = fs::read_to_string("day13.txt").expect("Should have read the file");
    let short_text = "#.##..##.
..#.##.#.
##......#
##......#
..#.##.#.
..##..##.
#.#.##.#.

#...##..#
#....#..#
..##..###
#####.##.
#####.##.
..##..###
#....#..#";

    let bugged = "###.#...#..###...
######.##.#..#...
###...###....###.
####..#..##....##
...###.#..##...##
.#...###.####...#
.#...###.####...#
...##..#..##...##
####..#..##....##
###...###....###.
######.##.#..#...
###.#...#..###...
###.#...#..###...";

    assert_eq!(day_13_1(short_text), 405);
    assert_eq!(day_13_1(bugged), 1200);

    let ans_13_1 = day_13_1(&text);
    println!("day 13_1 = {}", ans_13_1);
    assert_eq!(ans_13_1, 33735);

    // Part 2
    let broken = "########...#.
.#...#.......
##.##.#...##.
####.#.##.##.
..#..##...#.#
##.##.#.#.#..
#.####....###
#.##.#..#####
#.##.#..#####
#.####....###
##.##.#.#.#.#
##.##.#.#.#.#
#.####....###
#.##.#..#####
#.##.#..#####
#.####....###
##.##.#.#.#..";

    //env::set_var("RUST_BACKTRACE", "1");

    assert_eq!(day_13_2(short_text), 400);
    assert_eq!(day_13_2(broken), 1400);

    let ans_13_2 = day_13_2(&text);
    println!("day 13_2 = {}", ans_13_2);
    assert_eq!(ans_13_2, 38063);
}
